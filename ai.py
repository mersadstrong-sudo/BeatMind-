import os

from openai import AsyncOpenAI


# =========================================================
# BeatMind AI Lyrics Engine
# =========================================================

async def generate_lyrics(
    style,
    mood,
    topic,
    flow,
):

    api_key = os.getenv(
        "OPENAI_API_KEY",
        "",
    ).strip()


    # -----------------------------------------------------
    # Offline fallback
    # -----------------------------------------------------

    if not api_key:

        return offline_lyrics(
            style,
            mood,
            topic,
            flow,
        )


    # -----------------------------------------------------
    # OpenAI Client
    # -----------------------------------------------------

    client = AsyncOpenAI(
        api_key=api_key
    )


    model = os.getenv(
        "OPENAI_MODEL",
        "gpt-4o-mini",
    )


    # -----------------------------------------------------
    # System Prompt
    # -----------------------------------------------------

    system_prompt = """
تو موتور تولید تکست BeatMind هستی.

وظیفه تو نوشتن تکست‌های کاملاً اورجینال فارسی برای
خواننده‌ها و هنرمندان مستقل است.

قوانین:

1. متن باید کاملاً جدید و اورجینال باشد.
2. متن یا سبک نوشتاری یک خواننده مشخص را کپی نکن.
3. از بازسازی یا ادامه دادن متن آهنگ‌های موجود خودداری کن.
4. ساختار حرفه‌ای آهنگ داشته باش.
5. قافیه و ریتم فارسی طبیعی باشد.
6. متن قابل اجرا و خواندن باشد.
7. از کلیشه‌های بیش از حد استفاده نکن.
8. متناسب با ژانر و حس انتخاب‌شده بنویس.
9. در صورت مناسب بودن از Hook قدرتمند استفاده کن.
10. زبان خروجی فارسی باشد.

ساختار پیشنهادی:

[INTRO]

[VERSE 1]

[PRE-HOOK]

[HOOK]

[VERSE 2]

[BRIDGE]

[HOOK]

[OUTRO]
"""


    # -----------------------------------------------------
    # User Prompt
    # -----------------------------------------------------

    user_prompt = f"""
برای BeatMind یک آهنگ فارسی اورجینال بساز.

Style:
{style}

Mood:
{mood}

Topic:
{topic}

Flow:
{flow}

لطفاً متن را به شکل حرفه‌ای و قابل اجرا بنویس.

ساختار آهنگ را حفظ کن.
"""


    # -----------------------------------------------------
    # AI Request
    # -----------------------------------------------------

    response = await client.chat.completions.create(

        model=model,

        messages=[
            {
                "role": "system",
                "content": system_prompt,
            },
            {
                "role": "user",
                "content": user_prompt,
            },
        ],

        temperature=0.9,

        max_tokens=2200,
    )


    # -----------------------------------------------------
    # Result
    # -----------------------------------------------------

    result = (
        response
        .choices[0]
        .message
        .content
    )


    if not result:

        return offline_lyrics(
            style,
            mood,
            topic,
            flow,
        )


    return result.strip()


# =========================================================
# Offline Fallback
# =========================================================

def offline_lyrics(
    style,
    mood,
    topic,
    flow,
):

    return f"""
[INTRO]

شب افتاده و شهر هنوز بیداره
یه حرف مونده که توی قلبم جا داره


[VERSE 1]

گفتم از اینجا به بعد راه خودمو می‌رم
ولی هر قدم دوباره سمت خاطره برمی‌گردم

موضوع من و تو هنوز توی ذهنم زنده‌ست
هرچی دورتر می‌شم این حس نزدیک‌تره

خیابون پر نوره ولی قلبم تاریکه
یه چیزی توی سینه هنوز دنبال تکیه‌گاهه


[PRE-HOOK]

شاید این آخر راه نباشه
شاید یه فردای تازه باشه


[HOOK]

اگه بری این شهر بدون تو ساکته
اگه بمونی شاید دوباره شروع شه

من هنوز بین رفتن و موندن گیرم
ولی این بار می‌خوام خودمو پیدا کنم


[VERSE 2]

صدای خیابون، نور سرد پنجره
یه عالمه سؤال که جوابشون کجاست

من از شکستام یه مسیر تازه ساختم
تا برسم به جایی که خودم می‌خوام

دیگه نمی‌ترسم از شبای طولانی
حتی اگه تنها بمونم توی خیابون

چون فهمیدم آخر هر سقوطی
می‌تونه شروع یه پرواز باشه


[BRIDGE]

من همون آدم دیروزم
ولی دیگه مثل قبل نیستم

هرچی ازم گرفت این دنیا
یه چیزی تازه بهم یاد داد


[HOOK]

اگه بری این شهر بدون تو ساکته
اگه بمونی شاید دوباره شروع شه

من هنوز بین رفتن و موندن گیرم
ولی این بار می‌خوام خودمو پیدا کنم


[OUTRO]

Style: {style}
Mood: {mood}
Flow: {flow}
Topic: {topic}
"""
